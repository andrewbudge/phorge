#define _POSIX_C_SOURCE 200809L

#include "cli_help.h"

#include <stdio.h>
#include <string.h>

static void print_help_to(FILE *stream, const char *cmd) {
    if (!cmd) {
        fputs("phorge - composable file tools for phylogenetics\n"
              "\n"
              "Usage: phorge <command> [options]\n"
              "\n"
              "Commands:\n"
              "  getheaders (ghd)  Extract headers from FASTA files (stdin if no FILE)\n"
              "  stats             Alignment summary statistics\n"
              "  filter            Drop taxa exceeding a missingness threshold\n"
              "  convert           Convert FASTA / NEXUS / PHYLIP sequences\n"
              "  curate            Trim alignment columns (ClipKIT-style modes)\n"
              "  concat (liger)    Build a supermatrix from multiple alignments\n"
              "  coverage          Summarize taxa/loci coverage from a provenance TSV\n"
              "  align (aln)       Batch align FASTA files with MAFFT or MUSCLE\n"
              "  extract           Extract gene regions with MMseqs2 homology search\n"
              "  dump              Fetch GenBank records via NCBI E-utilities for extract\n"
              "  unpack            Unpack an NCBI Datasets zip into a directory\n"
              "  harvest           Collect FASTA files from an unpacked dataset\n"
              "  report            Build a query TSV from an unpacked dataset\n"
              "  orthologs (groups) Split Datasets records into per-orthogroup FASTAs\n"
              "  rip               Extract annotated genes from GenBank (SeqRipper port)\n"
              "\n"
              "Run 'phorge <command> --help' for command-specific help.\n", stream);
        return;
    }
    if (!strcmp(cmd, "getheaders")) {
        fputs("Usage: phorge getheaders [-u|--unique] [FILE ...]\n"
              "\n"
              "Extract headers from FASTA files, in file order. Reads stdin if no FILE\n"
              "is given. Multiple input files are processed in order.\n"
              "\n"
              "Arguments:\n"
              "  [FILE ...]       Input FASTA files\n"
              "\n"
              "Options:\n"
              "  -u, --unique     Print only unique headers (deduplicate)\n"
              "  -h, --help       Print this help\n", stream);
    } else if (!strcmp(cmd, "stats")) {
        fputs("Usage: phorge stats [-d|--detailed] [-p|--pretty] FILE ...\n"
              "\n"
              "Summarize FASTA alignments: sequence count, length, data type, GC%,\n"
              "missingness, and (for equal-length alignments) variable/informative sites.\n"
              "\n"
              "Arguments:\n"
              "  FILE ...         FASTA files to summarize\n"
              "\n"
              "Options:\n"
              "  -d, --detailed   Per-sequence rows (header, length, GC%, missingness)\n"
              "  -p, --pretty     Column-aligned output instead of TSV\n"
              "  -h, --help       Print this help\n", stream);
    } else if (!strcmp(cmd, "filter")) {
        fputs("Usage: phorge filter [-m F] [-l TSV] [-n N] FILE\n"
              "\n"
              "Remove taxa from an aligned FASTA that exceed a missingness threshold or\n"
              "fall below a minimum number of loci. Kept sequences go to stdout.\n"
              "\n"
              "Arguments:\n"
              "  FILE             Aligned FASTA (all sequences must be the same length)\n"
              "\n"
              "Options:\n"
              "  -m, --max-missing F   Maximum fraction of '-', 'N', 'X', '?' (0.0-1.0)\n"
              "  -l, --log TSV         Provenance TSV from 'concat -l' (used with -n)\n"
              "  -n, --min-loci N      Minimum loci a taxon must be present in\n"
              "  -h, --help            Print this help\n", stream);
    } else if (!strcmp(cmd, "convert")) {
        fputs("Usage: phorge convert -o FORMAT FILE\n"
              "\n"
              "Detect the input format from its contents (FASTA, NEXUS, or PHYLIP) and\n"
              "write the sequences in the requested output format to stdout.\n"
              "\n"
              "Arguments:\n"
              "  FILE             Input sequence file\n"
              "\n"
              "Options:\n"
              "  -o, --output_format FORMAT   Output format (required):\n"
              "                                 f / fasta      FASTA\n"
              "                                 n / nexus/nex  NEXUS\n"
              "                                 sp             strict PHYLIP (10-char names)\n"
              "                                 rp / phylip    relaxed PHYLIP\n"
              "  -h, --help                   Print this help\n", stream);
    } else if (!strcmp(cmd, "curate")) {
        fputs("Usage: phorge curate [-k KEEP] [--gap-threshold F] [-e EXT] [-o DIR] FILE ...\n"
              "\n"
              "Trim alignment columns with ClipKIT-compatible modes. With no -o, the\n"
              "trimmed alignment is written to stdout and a summary to stderr.\n"
              "\n"
              "Arguments:\n"
              "  FILE ...         Aligned FASTA files (equal-length sequences required)\n"
              "\n"
              "Options:\n"
              "  -k, --keep KEEP  Columns to keep; combine letters (default: ps):\n"
              "                     p  parsimony-informative sites\n"
              "                     c  constant sites\n"
              "                     s  smart-gap threshold (auto from gap distribution)\n"
              "                     g  fixed gap threshold\n"
              "      --gap-threshold F   Maximum gappiness for 'g' modes (default: 0.9)\n"
              "  -e, --extension EXT     Suffix for output filenames (default: _curated)\n"
              "  -o, --output DIR        Write curated files to DIR instead of stdout\n"
              "  -h, --help              Print this help\n", stream);
    } else if (!strcmp(cmd, "concat")) {
        fputs("Usage: phorge concat [-a TAXA] [-f FORMAT] [-m CHAR] [-p PARTITIONS]\n"
              "                      [-l LOG] [--dry-run] FILE ...\n"
              "\n"
              "Concatenate per-gene alignments into a supermatrix. Without -a, taxa are\n"
              "the union of FASTA headers (exact match); with -a, headers are matched to\n"
              "a taxa list by case-insensitive substring search.\n"
              "\n"
              "Arguments:\n"
              "  FILE ...         Aligned FASTA files (one per gene)\n"
              "\n"
              "Options:\n"
              "  -a, --alias TAXA        Taxa list for smart matching (one name per line)\n"
              "  -f, --format FORMAT     Output: fasta (default) or nexus\n"
              "  -m, --missing CHAR      Missing-data character (default N, X, or ?)\n"
              "  -p, --partitions FMT    Partition output: raxml (default) or nexus\n"
              "  -l, --log PATH          Provenance TSV (required with -a)\n"
              "      --dry-run           Show matching summary without building matrix\n"
              "  -h, --help              Print this help\n", stream);
    } else if (!strcmp(cmd, "coverage")) {
        fputs("Usage: phorge coverage [-t|--taxa | -l|--loci] [-p|--pretty] TSV\n"
              "\n"
              "Summarize coverage from the provenance TSV written by 'concat -l'.\n"
              "\n"
              "Arguments:\n"
              "  TSV              Provenance TSV (header row = locus names)\n"
              "\n"
              "Options:\n"
              "  -t, --taxa       Per-taxon coverage (one view is required)\n"
              "  -l, --loci       Per-locus coverage\n"
              "  -p, --pretty     Column-aligned output instead of TSV\n"
              "  -h, --help       Print this help\n", stream);
    } else if (!strcmp(cmd, "align")) {
        fputs("Usage: phorge align [-p PROG] [-e SUFFIX] -o DIR FILE ... [-- ALIGNER_FLAGS]\n"
              "\n"
              "Batch-align unaligned FASTA files with MAFFT or MUSCLE. Aligner stderr\n"
              "is appended to DIR/align.log.\n"
              "\n"
              "Arguments:\n"
              "  FILE ...         Unaligned FASTA files\n"
              "\n"
              "Options:\n"
              "  -p, --program PROG   Aligner name or path (default: mafft)\n"
              "  -e, --extension SUF  Output filename suffix (default: _aln)\n"
              "  -o, --output DIR     Output directory (required)\n"
              "      -- FLAGS         Flags passed to the aligner, replacing the default\n"
              "  -h, --help           Print this help\n", stream);
    } else if (!strcmp(cmd, "extract")) {
        fputs("Usage: phorge extract (--reference REF | --refs DIR|FILE) -o DIR TARGET ...\n"
              "\n"
              "Find gene regions in target FASTAs with MMseqs2 and write one FASTA per\n"
              "gene. Minus-strand hits are reverse-complemented into reference orientation.\n"
              "\n"
              "Arguments:\n"
              "  TARGET ...           Target FASTA files or directories\n"
              "\n"
              "Options:\n"
              "  -r, --reference REF  Single multi-gene reference FASTA\n"
              "      --refs PATH      Per-gene reference FASTA or directory (repeatable)\n"
              "  -o, --output DIR     Output directory (required)\n"
              "  -m, --min-identity F Minimum identity (default: 0.7)\n"
              "  -c, --coverage F     Minimum fraction of reference covered (default: 0.5)\n"
              "      --flank N        Extra bases on each side (default: 0)\n"
              "  -s, --sensitivity F  MMseqs2 sensitivity (default: 5.7)\n"
              "      --max-seqs N     Max targets per reference (default: 300)\n"
              "      --max-memory-limit S  MMseqs2 RAM cap (e.g. 8G)\n"
              "      --kmer-length N  MMseqs2 k-mer length (default: 13; 0 = auto)\n"
              "      --keep-intermediates   Keep MMseqs2 work files\n"
              "  -h, --help           Print this help\n", stream);
    } else if (!strcmp(cmd, "dump")) {
        fputs("Usage: phorge dump -q QUERY -o FILE [--format fasta|gb]\n"
              "                   [--query-file FILE] [--ids FILE] [--ids-out FILE]\n"
              "                   [--db DB] [--limit N] [--batch N]\n"
              "                   [--dry-run] [--force]\n"
              "\n"
              "Fetch sequence records from NCBI E-utilities (ESearch + batched EFetch)\n"
              "into one FASTA (for phorge extract) or GenBank flat file (for rip).\n"
              "With --ids-out, run ESearch only and write the UIDs (use '-' for stdout,\n"
              "e.g. --ids-out - | wc -l for a count), then feed them back with --ids.\n"
              "Coarse filtering uses standard Entrez query terms such as\n"
              "'Odonata[ORGN] AND COX1[GENE]' or 'txid6961[ORGN] AND 1000:20000[SLEN]'.\n"
              "An NCBI API key is read from the NCBI_API_KEY environment variable;\n"
              "requests are paced to 3/s without a key, 10/s with one.\n"
              "\n"
              "Arguments:\n"
              "  -q, --query TERM    Entrez query; use @FILE to read it from a file\n"
              "      --query-file F  Read the Entrez query from F (newlines become spaces)\n"
              "      --ids FILE      Read UIDs directly, one per line\n"
              "\n"
              "Options:\n"
              "  -o, --output FILE   Output file (required unless --ids-out is used)\n"
              "      --ids-out FILE  Write matched UIDs and stop; '-' means stdout\n"
              "      --format F      fasta (default) or gb (GenBank with features)\n"
              "      --db DB         Entrez database (default: nuccore)\n"
              "  -n, --limit N       Fetch at most N records (default: all matches)\n"
              "      --batch N       UIDs per EFetch request (default: 200)\n"
              "      --dry-run       Print the match count only; do not download\n"
              "      --force         Overwrite an existing output file\n"
              "  -h, --help          Print this help\n"
              "\n"
              "A provenance sidecar FILE.dump.json records the query, counts and date.\n"
              "curl must be installed and in PATH.\n", stream);
    } else if (!strcmp(cmd, "unpack")) {
        fputs("Usage: phorge unpack ZIP [-o DIR] [--list] [--force] [--prune-zip]\n"
              "\n"
              "Unpack an NCBI Datasets zip archive. A sorted manifest (path, uncompressed\n"
              "bytes, compressed bytes) is written to stdout; a summary goes to stderr.\n"
              "Unsafe paths (absolute, '..', backslashes) are rejected.\n"
              "\n"
              "Options:\n"
              "  -o, --output DIR   Destination (default: ZIP basename without .zip)\n"
              "      --list         List entries without extracting\n"
              "      --force        Overwrite existing files\n"
              "      --prune-zip    Delete the zip after a successful extraction\n"
              "  -h, --help         Print this help\n", stream);
    } else if (!strcmp(cmd, "harvest")) {
        fputs("Usage: phorge harvest DIR [-o OUTDIR] [--decompress] [--force]\n"
              "\n"
              "Collect FASTA files (.fna/.faa/.fasta/.fa/.ffn/.fas, optionally .gz) from\n"
              "an unpacked dataset into one flat directory. Duplicate names are disambiguated\n"
              "with the parent directory name. A sorted manifest (output, source, bytes) is\n"
              "written to stdout.\n"
              "\n"
              "Options:\n"
              "  -o, --output DIR   Destination (default: DIR/fasta)\n"
              "      --decompress   Decompress .gz inputs on copy\n"
              "      --force        Overwrite existing files\n"
              "  -h, --help         Print this help\n", stream);
    } else if (!strcmp(cmd, "report")) {
        fputs("Usage: phorge report DIR|ZIP [-o TSV] [--query-taxid N] [--group ingroup|outgroup]\n"
              "\n"
              "Build phorge's query TSV from an unpacked NCBI Datasets directory, or\n"
              "directly from the downloaded zip. Joins\n"
              "FASTA headers (accession, organism, GeneID) with data_report.jsonl /\n"
              "annotation_report.jsonl. Rows are sorted by accession. Handles both\n"
              "eukaryotic (rna.fna/protein.faa) and prokaryotic (gene.fna) packages.\n"
              "\n"
              "Options:\n"
              "  -o, --output TSV     Output file (default: stdout)\n"
              "      --query-taxid N  Stamp the queried taxonomic root (default: per-row taxid)\n"
              "      --group G        ingroup or outgroup (default: ingroup)\n"
              "  -h, --help           Print this help\n", stream);
    } else if (!strcmp(cmd, "orthologs")) {
        fputs("Usage: phorge orthologs DIR|ZIP [-o DIR] [--fasta NAME] [--keep-all]\n"
              "                            [--id taxid|name] [--force]\n"
              "\n"
              "Split an NCBI Datasets ortholog package into one FASTA per orthogroup,\n"
              "ready for curate/concat. Groups come from geneGroups in data_report.jsonl;\n"
              "FASTA records are joined by [GeneID=...]. By default the longest sequence\n"
              "per taxon is kept and headers are taxon names. Writes orthologs.tsv.\n"
              "\n"
              "Options:\n"
              "  -o, --output DIR     Output directory (default: <input>_orthologs)\n"
              "      --fasta NAME     Use only this FASTA (default: cds.fna > rna.fna >\n"
              "                       gene.fna > protein.faa)\n"
              "      --keep-all       Keep every isoform/record, not just the longest\n"
              "      --id taxid|name  Header uses taxid instead of taxon name\n"
              "      --force          Overwrite an existing orthologs.tsv\n"
              "  -h, --help           Print this help\n", stream);
    } else if (!strcmp(cmd, "rip")) {
        fputs("Usage: phorge rip (-g GENES | --all) -o DIR FILE.gb ...\n"
              "\n"
              "Port of SeqRipper: extract selected loci from mitochondrial GenBank\n"
              "genomes into one FASTA per gene per genome. Specific to mitochondrial\n"
              "annotations; does not locate loci in general GenBank files. Handles the\n"
              "standard mt gene synonyms (COI/COX1, CYTB, 12S, 16S, ND1-ND6, ...),\n"
              "complement()/join() locations, and writes seqripper_log.tsv.\n"
              "\n"
              "Options:\n"
              "  -g, --genes LIST   Comma-separated genes to extract (e.g. COI,CYTB,12S)\n"
              "      --all          Extract all annotated genes\n"
              "      --no-trna      Skip tRNAs (with --all)\n"
              "  -a, --aggregate    Aggregate by canonical gene into one multi-FASTA per\n"
              "                     gene, e.g. COI.fasta; collapse gene/CDS duplicates\n"
              "  -o, --output DIR   Output directory (required)\n"
              "  -v, --verbose      Per-file/per-gene detail on stderr\n"
              "  -q, --quiet        Suppress the summary\n"
              "  -h, --help         Print this help\n", stream);
    } else {
        fputs("Unknown command. Run 'phorge --help' for the command list.\n", stream);
    }
}

void print_help(const char *cmd) { print_help_to(stdout, cmd); }

void print_usage(void) { print_help_to(stderr, NULL); }
